package bd.shromikai.eval;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

import bd.shromikai.testsupport.Requirement;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

/**
 * FR-80, R-07: the report is generated, never written by hand. Limitations, known failures and the
 * number of reviewed labels always appear; every proportion has its count; a metric that is missing
 * (rather than reported as not available, not done or not run) stops generation.
 */
@Tag("unit")
@Requirement("FR-80")
class ReportGeneratorTest {

  @TempDir Path dir;

  private static EvalReport.Config config(int reviewed) {
    return new EvalReport.Config(
        "r1",
        "2026-11-17T10:00:00Z",
        "abc1234",
        true,
        "2026.11.11-1",
        "contracts",
        "dev",
        List.of("baseline", "shromikai"),
        1,
        List.of("syn-en-02", "syn-bn-01"),
        Map.of("REASONING", "claude-sonnet-5-5"),
        Map.of("risk-analysis", 2),
        "SAME_FAMILY",
        "Apple M3, 16 GB, Docker Ollama without GPU",
        420_000,
        2_300_000,
        42,
        5,
        reviewed,
        73,
        0,
        "5 synthetic contracts (team-authored), dev split");
  }

  private static Map<String, MetricResult> allNotRun() {
    Map<String, MetricResult> out = new LinkedHashMap<>();
    for (String id : MetricCatalog.ids()) {
      out.put(id, MetricResult.notRun(id, "toy"));
    }
    return out;
  }

  private static EvalReport report(Map<String, MetricResult> shromikai, int reviewed) {
    Map<String, MetricResult> baseline = new LinkedHashMap<>();
    baseline.put("M-03", MetricResult.proportion("M-03", 3, 10, "objective checks"));
    return new EvalReport(
        config(reviewed),
        Map.of("shromikai", shromikai, "baseline", baseline),
        List.of(new EvalReport.Ablation("no-verifier", "derived from the same runs", Map.of())),
        List.of("syn-bn-02 baseline: model-output-invalid"),
        List.of("Small sample: 3 contracts."),
        List.of("BLA-2006:3 transfer finding verified although weakly related."),
        List.of());
  }

  @Test
  void shouldWriteBothFilesWithTheRequiredSections() throws IOException {
    Map<String, MetricResult> metrics = allNotRun();
    metrics.put("M-05", MetricResult.proportion("M-05", 19, 20, "adversarial set"));
    metrics.put("M-27", MetricResult.notAvailable("M-27", "no reviewer verdict files"));
    metrics.put("M-21", MetricResult.notDone("M-21", "LLM-as-judge cut"));

    ReportGenerator.write(report(metrics, 0), dir);

    String md = Files.readString(dir.resolve("report.md"));
    assertThat(md)
        .contains("# Evaluation report r1")
        .contains("## Configuration")
        .contains("## Headline: baseline vs ShromikAI")
        .contains("## All metrics")
        .contains("## Ablations")
        .contains("## Bias: bilingual consistency and side balance")
        .contains("## Failures and abstentions")
        .contains("## Limitations")
        .contains("## Known failures")
        .contains("## Errata")
        .contains("0 reviewed labels")
        .contains("0.950 (19 of 20)")
        .contains("not available: no reviewer verdict files")
        .contains("not done: LLM-as-judge cut")
        .contains("abc1234")
        .contains("2026.11.11-1")
        .contains("generated by the evaluation runner; do not edit by hand");
    assertThat(md).doesNotContainPattern("\\d+(\\.\\d+)? ?%(?! \\()");

    JsonNode json = new ObjectMapper().readTree(dir.resolve("report.json").toFile());
    assertThat(json.fieldNames())
        .toIterable()
        .contains(
            "config",
            "headline",
            "metrics",
            "ablations",
            "bias",
            "failures",
            "limitations",
            "knownFailures",
            "errata",
            "provenance");
    JsonNode m05 = json.get("metrics").get("shromikai").get("M-05");
    assertThat(m05.get("value").asDouble()).isEqualTo(0.95);
    assertThat(m05.get("count").asLong()).isEqualTo(19);
    assertThat(m05.get("n").asLong()).isEqualTo(20);
    assertThat(m05.get("ci95")).hasSize(2);
    assertThat(m05.get("target").asText()).isEqualTo("≥ 0.90");
    assertThat(m05.get("met").asBoolean()).isTrue();
    assertThat(json.get("config").get("reviewedLabelFiles").asInt()).isZero();
    assertThat(json.get("provenance").get("gitSha").asText()).isEqualTo("abc1234");
    assertThat(json.get("metrics").get("shromikai").get("M-27").get("status").asText())
        .isEqualTo("NOT_AVAILABLE");
  }

  @Test
  void shouldFailWhenAMetricIsMissing() {
    Map<String, MetricResult> metrics = allNotRun();
    metrics.remove("M-14");
    assertThatThrownBy(() -> ReportGenerator.write(report(metrics, 0), dir))
        .hasMessageContaining("M-14");
  }

  @Test
  void shouldAlwaysListLimitationsAndKnownFailuresEvenWhenEmpty() throws IOException {
    EvalReport empty =
        new EvalReport(
            config(0),
            Map.of("shromikai", allNotRun()),
            List.of(),
            List.of(),
            List.of(),
            List.of(),
            List.of());
    assertThatThrownBy(() -> ReportGenerator.write(empty, dir)).hasMessageContaining("Limitations");
  }

  @Test
  void shouldStateTheNumberOfReviewedLabels() throws IOException {
    ReportGenerator.write(report(allNotRun(), 2), dir);
    assertThat(Files.readString(dir.resolve("report.md"))).contains("2 of 5 label files reviewed");
  }

  @Test
  void shouldKeepEveryRunInItsOwnFolder() throws IOException {
    Path runs = dir.resolve("runs");
    ReportGenerator.writeRun(report(allNotRun(), 0), dir);
    assertThat(Files.isRegularFile(dir.resolve("report.json"))).isTrue();
    try (var s = Files.list(runs)) {
      Path run = s.findFirst().orElseThrow();
      assertThat(run.getFileName().toString()).isEqualTo("2026-11-17-r1");
      assertThat(Files.isRegularFile(run.resolve("report.md"))).isTrue();
      assertThat(Files.isRegularFile(run.resolve("config.json"))).isTrue();
    }
  }

  @Test
  void shouldNotCallUnresolvableBaselineCitationsFabricatedAndShowTheIndependentCatchRateApart()
      throws IOException {
    Map<String, MetricResult> metrics = allNotRun();
    metrics.put(
        "M-04",
        MetricResult.proportion(
            "M-04",
            73,
            73,
            "adversarial set plus baseline",
            Map.of(
                "misses", 0L,
                "adversarialCaught", 52L,
                "adversarialFabricated", 52L,
                "baselineCaught", 21L,
                "baselineFabricated", 21L,
                "rawAgentCaught", 0L,
                "rawAgentFabricated", 0L)));
    Map<String, MetricResult> baseline = new LinkedHashMap<>();
    baseline.put(
        "M-03",
        MetricResult.proportion(
            "M-03",
            21,
            21,
            "BASELINE claims",
            Map.of(
                "unresolvedByKeyShape",
                new java.util.TreeMap<>(
                    Map.of("contract-clause-reference", 17L, "malformed-statute-reference", 4L)))));
    EvalReport report =
        new EvalReport(
            config(0),
            Map.of("shromikai", metrics, "baseline", baseline),
            List.of(),
            List.of(),
            List.of("Small sample."),
            List.of(),
            List.of());

    ReportGenerator.write(report, dir);

    JsonNode json = new ObjectMapper().readTree(dir.resolve("report.json").toFile());
    JsonNode m03 = headlineRow(json, "M-03");
    assertThat(m03.get("metric").asText()).doesNotContainIgnoringCase("fabricated");
    assertThat(m03.get("baseline").asText())
        .contains("not resolvable against the corpus")
        .contains("1.000 (21 of 21)")
        .contains("17 cite the contract's own clauses")
        .contains("4 malformed keys");
    JsonNode m04 = headlineRow(json, "M-04");
    assertThat(m04.get("shromikai").asText())
        .contains("1.000 (52 of 52)")
        .contains("independent")
        .contains("21 of 21 baseline")
        .contains("same check");
    assertThat(m04.get("shromikai").asText()).doesNotContain("73 of 73");
    // The per-metric entry keeps the full figures; only the headline cell is qualified.
    assertThat(json.get("metrics").get("shromikai").get("M-04").get("count").asLong())
        .isEqualTo(73);

    String md = Files.readString(dir.resolve("report.md"));
    String headline = md.substring(md.indexOf("## Headline"), md.indexOf("## All metrics"));
    assertThat(headline).contains("not resolvable against the corpus").contains("1.000 (52 of 52)");
    assertThat(headline.lines().filter(l -> l.startsWith("| M-03")).findFirst().orElseThrow())
        .doesNotContainIgnoringCase("fabricated");
  }

  private static JsonNode headlineRow(JsonNode json, String id) {
    for (JsonNode row : json.get("headline")) {
      if (id.equals(row.get("id").asText())) {
        return row;
      }
    }
    throw new AssertionError("no headline row " + id);
  }
}
