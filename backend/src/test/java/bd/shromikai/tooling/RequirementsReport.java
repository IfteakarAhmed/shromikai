package bd.shromikai.tooling;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;
import java.util.stream.Stream;

/**
 * {@code ./gradlew requirementsReport}: requirement ID to tests, from {@code @Requirement}
 * annotations and Vitest/Playwright titles (test-strategy.md §18). Writes Markdown.
 */
public final class RequirementsReport {

  private static final Pattern ANNOTATION =
      Pattern.compile("@Requirement\\(\"([A-Z]+-[0-9]+)\"\\)");
  private static final Pattern TITLE =
      Pattern.compile("\\b(?:it|test)\\(\\s*['\"`]((?:FR|NFR|KPI|M|T)-[0-9]+)\\b");

  private RequirementsReport() {}

  public static void main(String[] args) throws IOException {
    Map<String, Set<String>> report = collect(Path.of(args[0]), Path.of(args[1]));
    Path out = Path.of(args[2]);
    Files.createDirectories(out.getParent());
    Files.writeString(out, render(report));
    System.out.println("requirementsReport: " + report.size() + " requirements -> " + out);
  }

  static Map<String, Set<String>> collect(Path javaTests, Path frontend) throws IOException {
    Map<String, Set<String>> report = new TreeMap<>(RequirementsReport::compareIds);
    scan(javaTests, ".java", ANNOTATION, report);
    if (Files.isDirectory(frontend)) {
      scan(frontend, ".test.ts", TITLE, report);
      scan(frontend, ".test.tsx", TITLE, report);
    }
    return report;
  }

  private static void scan(
      Path root, String suffix, Pattern pattern, Map<String, Set<String>> report)
      throws IOException {
    List<Path> files;
    try (Stream<Path> walk = Files.walk(root)) {
      files = walk.filter(p -> p.toString().endsWith(suffix)).sorted().toList();
    }
    for (Path file : files) {
      if (file.toString().contains("node_modules")) {
        continue;
      }
      Matcher matcher = pattern.matcher(Files.readString(file));
      String name = file.getFileName().toString();
      while (matcher.find()) {
        report.computeIfAbsent(matcher.group(1), id -> new TreeSet<>()).add(name);
      }
    }
  }

  static String render(Map<String, Set<String>> report) {
    List<String> lines = new ArrayList<>();
    lines.add("# Requirement coverage");
    lines.add("");
    lines.add("Generated by `./gradlew requirementsReport` (test-strategy.md §18).");
    lines.add("");
    lines.add("| Requirement | Tests |");
    lines.add("| --- | --- |");
    report.forEach((id, tests) -> lines.add("| " + id + " | " + String.join(", ", tests) + " |"));
    return String.join("\n", lines) + "\n";
  }

  /** FR-2 before FR-10. */
  static int compareIds(String a, String b) {
    String[] left = a.split("-");
    String[] right = b.split("-");
    int prefix = left[0].compareTo(right[0]);
    return prefix != 0
        ? prefix
        : Integer.compare(Integer.parseInt(left[1]), Integer.parseInt(right[1]));
  }
}
