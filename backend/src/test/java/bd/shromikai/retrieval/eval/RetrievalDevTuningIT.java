package bd.shromikai.retrieval.eval;

import static org.assertj.core.api.Assertions.assertThat;

import bd.shromikai.retrieval.RetrievalMetrics;
import bd.shromikai.retrieval.RetrievalMetrics.Outcome;
import bd.shromikai.retrieval.RetrievalMetrics.Summary;
import bd.shromikai.retrieval.RetrievalService;
import bd.shromikai.retrieval.SearchOptions;
import bd.shromikai.retrieval.TextTuning;
import bd.shromikai.retrieval.eval.RetrievalEvalRunner.Question;
import bd.shromikai.testsupport.Requirement;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Instant;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.Tag;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.ActiveProfiles;

/**
 * FR-23 / ADR-0013: tunes the full-text query on the {@code dev} question set only ({@code
 * eval/retrieval/dev-questions.jsonl}) and writes {@code eval/reports/retrieval-dev.md}. The test
 * split ({@code questions.jsonl}) is never read here. The selection rule is fixed before the run:
 * highest hybrid + graph hit@5, then MRR@10, then fewer enabled knobs.
 */
@Tag("eval")
@Requirement("FR-23")
@SpringBootTest(webEnvironment = SpringBootTest.WebEnvironment.RANDOM_PORT)
@ActiveProfiles("eval")
class RetrievalDevTuningIT {

  record Variant(String name, TextTuning tuning, int knobs) {}

  @Autowired RetrievalService retrieval;

  @Test
  void shouldRankTextQueryVariantsOnTheDevSet() throws IOException, InterruptedException {
    Path root = Path.of("..").toAbsolutePath().normalize();
    List<Question> questions =
        RetrievalEvalRunner.load(root.resolve("eval/retrieval/dev-questions.jsonl"));
    assertThat(questions.size()).isGreaterThanOrEqualTo(30);

    List<Variant> variants = new ArrayList<>();
    variants.add(new Variant("untuned (P4 first run)", TextTuning.OFF, 0));
    for (double df : new double[] {0.20, 0.10, 0.05}) {
      variants.add(new Variant("df ≤ " + df, new TextTuning(df, false), 1));
    }
    variants.add(new Variant("language filter", new TextTuning(1.0, true), 1));
    for (double df : new double[] {0.20, 0.10, 0.05}) {
      variants.add(new Variant("df ≤ " + df + " + language filter", new TextTuning(df, true), 2));
    }

    SearchOptions base = new SearchOptions(SearchOptions.BD, 8, true, true, false, false, null);
    Map<String, SearchOptions> runs = new LinkedHashMap<>();
    runs.put("vector", base.withText(false));
    for (Variant v : variants) {
      runs.put(v.name() + "|text", base.withVector(false).withTextTuning(v.tuning()));
      runs.put(v.name() + "|hybrid", base.withTextTuning(v.tuning()));
      runs.put(v.name() + "|graph", base.withGraph(true).withTextTuning(v.tuning()));
    }
    RetrievalEvalRunner runner = new RetrievalEvalRunner(retrieval);
    Map<String, List<Outcome>> outcomes = runner.runVariants(questions, runs);
    Map<String, Summary> s = new LinkedHashMap<>();
    outcomes.forEach((k, v) -> s.put(k, RetrievalMetrics.summarise(v)));

    Variant selected =
        variants.stream()
            .max(
                Comparator.comparingInt((Variant v) -> s.get(v.name() + "|graph").hitsAt5())
                    .thenComparingDouble(v -> s.get(v.name() + "|graph").mrrAt10())
                    .thenComparingInt(v -> -v.knobs()))
            .orElseThrow();

    StringBuilder md = new StringBuilder();
    md.append("# Retrieval tuning on the dev set (FR-23, ADR-0013)\n\n");
    md.append("- Generated: ")
        .append(Instant.now())
        .append(" at git ")
        .append(gitSha(root))
        .append('\n');
    md.append(
        "- Generated by `RetrievalDevTuningIT` (`./gradlew evalRetrieval`); numbers computed by `RetrievalMetrics`.\n");
    md.append("- Questions: ")
        .append(questions.size())
        .append(
            " dev questions (`eval/retrieval/dev-questions.jsonl`), all `draft`; disjoint from the test set `eval/retrieval/questions.jsonl`, which this run never reads.\n");
    md.append(
        "- Selection rule, fixed before the run: highest hybrid + graph hit@5, then MRR@10, then fewer enabled knobs.\n");
    md.append("- Vector only (reference): hit@5 ")
        .append(fmt(s.get("vector")))
        .append(", MRR@10 ")
        .append(String.format("%.3f", s.get("vector").mrrAt10()))
        .append(".\n\n");
    md.append(
        "| Text query variant | Text only hit@5 | Hybrid hit@5 | Hybrid MRR@10 | Hybrid + graph hit@5 | Hybrid + graph MRR@10 | Hybrid + graph recall@8 |\n| --- | ---: | ---: | ---: | ---: | ---: | ---: |\n");
    for (Variant v : variants) {
      Summary t = s.get(v.name() + "|text");
      Summary h = s.get(v.name() + "|hybrid");
      Summary g = s.get(v.name() + "|graph");
      md.append("| ")
          .append(v.name())
          .append(" | ")
          .append(fmt(t))
          .append(" | ")
          .append(fmt(h))
          .append(" | ")
          .append(String.format("%.3f", h.mrrAt10()))
          .append(" | ")
          .append(fmt(g))
          .append(" | ")
          .append(String.format("%.3f", g.mrrAt10()))
          .append(" | ")
          .append(String.format("%.3f", g.recallAt8()))
          .append(" |\n");
    }
    md.append("\n**Selected by the rule: ")
        .append(selected.name())
        .append("** (max doc freq ")
        .append(selected.tuning().maxDocFreq())
        .append(", language filter ")
        .append(selected.tuning().languageFilter())
        .append(").\n");
    Files.writeString(
        root.resolve("eval/reports/retrieval-dev.md"), md.toString(), StandardCharsets.UTF_8);
    assertThat(s).isNotEmpty();
  }

  private static String fmt(Summary s) {
    return String.format("%.3f (%d/%d)", s.hitAt5(), s.hitsAt5(), s.questions());
  }

  private static String gitSha(Path root) throws IOException, InterruptedException {
    Process p =
        new ProcessBuilder("git", "rev-parse", "--short", "HEAD").directory(root.toFile()).start();
    String sha = new String(p.getInputStream().readAllBytes()).trim();
    p.waitFor(10, TimeUnit.SECONDS);
    return sha.isEmpty() ? "unknown" : sha;
  }
}
